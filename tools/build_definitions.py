"""Build definitions/definitions.tsv: the definition shown for every word in the word list.

Definitions are extracted from COED by coed_definitions.py, then checked:

- Each extracted definition gets flags for things extraction can get wrong
  (see FLAGS). Every flagged word must have a decision in
  definitions/review.tsv before the file can be built.
- definitions/review.tsv holds review decisions, one per line:
    word<TAB>ok<TAB>definition<TAB>note   the extracted definition is right
    word<TAB>fix<TAB>definition<TAB>note[<TAB>pos]  use this definition instead
                                           (pos: if it's a different part of speech)
  An "ok" records the text that was approved. If extraction later produces
  something different, the decision is stale and the word must be reviewed
  again.

Usage:
  python build_definitions.py                write definitions/definitions.tsv
  python build_definitions.py --check        fail if the file is stale or anything is unreviewed
  python build_definitions.py --unreviewed F write words needing review (word, flags, definition, senses) to F
"""

import argparse
import os
import re
import sys

from build_corpus import CORPUS
from coed_definitions import Definitions

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "definitions", "definitions.tsv")
REVIEW = os.path.join(HERE, "definitions", "review.tsv")

FLAGS = {
    "none": "COED gave no valid sense",
    "xref": "taken from another word the entry points to (right homograph and sense?)",
    "xref-unresolved": "still only points to another word",
    "self": "uses the word itself",
    "phrase": "only valid senses are tied to a set phrase",
    "offensive": "COED labels the only valid senses offensive, derogatory or vulgar",
    "capitalized": "only senses for a capitalized form, which RULES.md doesn't allow",
    "fallback": "adjective sense of an irregular comparative",
    "format": "leftover markup, IPA, or unbalanced brackets",
}
HEADER = "# Generated by build_definitions.py from COED and review.tsv. Do not edit by hand.\n"
REVIEW_HEADER = (
    "# Review decisions for definitions.tsv; see build_definitions.py.\n"
    "# word<TAB>ok|fix<TAB>definition<TAB>note[<TAB>pos, for a fix that changes part of speech]\n"
)
IPA_RE = re.compile(r"[ˈˌəʊɒɔːθðʃʒŋæɛɪʌα]|<|>|&|》|↘|\s[,.;:]|\(\s*\)")
XREF_TEXT_RE = re.compile(r"\b(variant|spelling) of\b|\(see |\bsee also\b|\bcompare with\b|\bin sense \d", re.I)


def flags_for(word, found):
    if found is None:
        return ["none"]
    flags = []
    d = found.definition
    if found.cross_ref:
        flags.append("xref")
    if found.unresolved or XREF_TEXT_RE.search(d):
        flags.append("xref-unresolved")
    if re.search(rf"\b{re.escape(word)}\b", d, re.I):
        flags.append("self")
    if found.sense.phrase:
        flags.append("phrase")
    if found.sense.capitalized:
        flags.append("capitalized")
    if found.sense.offensive:
        flags.append("offensive")
    if found.sense.fallback:
        flags.append("fallback")
    if IPA_RE.search(d) or d.count("(") != d.count(")"):
        flags.append("format")
    return flags


def read_review(path=REVIEW):
    review = {}
    if not os.path.exists(path):
        return review
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            fields = line.split("\t")
            if len(fields) < 3 or fields[1] not in ("ok", "fix") or not fields[2]:
                sys.exit(f"{path}:{n}: expected word<TAB>ok|fix<TAB>definition[<TAB>note]")
            note = fields[3] if len(fields) > 3 else ""
            pos = fields[4] if len(fields) > 4 else ""
            review[fields[0]] = (fields[1], fields[2], note, pos)
    return review


def build(coed=None):
    """Return (rows, problems). rows: (word, pos, definition, flags)."""
    coed = coed or Definitions()
    review = read_review()
    with open(CORPUS, encoding="utf-8") as f:
        words = [w.strip() for w in f if w.strip()]
    rows, problems = [], {"unreviewed": [], "stale": [], "unknown": []}
    for word in words:
        found = coed.lookup(word)
        flags = flags_for(word, found)
        definition = found.definition if found else ""
        pos = found.pos if found else ""
        decision = review.get(word)
        if decision:
            verdict, text, _, fix_pos = decision
            if verdict == "fix":
                definition = text
                pos = fix_pos or pos
                flags = flags + ["fixed"]
            elif text != definition:
                problems["stale"].append(word)
                continue
        elif flags:
            problems["unreviewed"].append(word)
        rows.append((word, pos, definition, flags))
    problems["unknown"] = sorted(set(review) - set(words))
    return rows, problems


def render(rows):
    lines = [HEADER, "# word\tpos\tdefinition\tflags\n"]
    lines += [f"{w}\t{p}\t{d}\t{','.join(f)}\n" for w, p, d, f in rows]
    return "".join(lines)


def report(problems):
    messages = {
        "unreviewed": "flagged words with no decision in review.tsv",
        "stale": "words whose 'ok' decision no longer matches the extracted definition",
        "unknown": "words in review.tsv that aren't in the word list",
    }
    failed = False
    for key, words in problems.items():
        if words:
            failed = True
            print(f"{len(words)} {messages[key]}: {', '.join(words[:20])}"
                  + (" ..." if len(words) > 20 else ""), file=sys.stderr)
    return failed


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="validate without writing")
    parser.add_argument("--unreviewed", help="write words needing review to this file")
    args = parser.parse_args(argv)

    coed = Definitions()
    rows, problems = build(coed)

    if args.unreviewed:
        todo = set(problems["unreviewed"]) | set(problems["stale"])
        with open(args.unreviewed, "w", encoding="utf-8") as f:
            for word in sorted(todo):
                found = coed.lookup(word)
                flags = flags_for(word, found)
                senses = " | ".join(f"{s.pos}: {s.definition}" for s in coed.senses(word))
                f.write(f"{word}\t{','.join(flags)}\t{found.definition if found else ''}\t{senses}\n")
        print(f"Wrote {len(todo)} words to {args.unreviewed}")
        return

    failed = report(problems)
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if not failed and current != render(rows):
            print(f"{OUT} is out of date: run build_definitions.py", file=sys.stderr)
            failed = True
        sys.exit(1 if failed else 0)
    if failed:
        sys.exit("Not written: review the words above first (--unreviewed lists them).")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(render(rows))
    flagged = sum(1 for r in rows if r[3])
    print(f"Wrote {len(rows)} definitions to {OUT} ({flagged} flagged, all reviewed)")


if __name__ == "__main__":
    main(sys.argv[1:])
